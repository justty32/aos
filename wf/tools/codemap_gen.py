#!/usr/bin/env python3
"""codemap_gen — 從 proto8 各檔檔頭的一句話生成逐檔 code map（wf/workflows/common/code-map/proto8/<夾>.md）。

  codemap_gen.py [--root REPO] [--apply] [--quiet]
    不帶 --apply：檢查。生成結果跟 commit 進去的冊一致就退 0；不一致（缺冊、內容不同、多出已不對應的生成冊）
                 每冊印一行 error 與差異、退 1。wf-lint 的 CODEMAP 就是跑這個。
    --apply      重寫生成冊；刪掉開頭帶 generated 標記、但已不對應任何夾的舊冊（手寫檔不碰）。
  一句話空或＝檔名：印 warning，不擋。

掃哪些檔：`git ls-files proto8`，去掉 thinking／archive／notes／user-advice／docs 夾、任何一層叫 archive／docs／
__pycache__ 的夾、.md（knowledge/ 除外）、.gitignore／.gitattributes、.vscode/。一個 proto8 頂層夾一冊（照實際夾名），
頂層單檔進 root 冊；冊超過約 7.5 KB 照第二層夾切成 <夾>-2.md…。

一句話怎麼認（使用者 11-05 裁「逐檔表改生成」，thinking 2026-11-05 arch-refactor 03 § 4）：
  C/C++ 第一行註解；腳本（含 _entry）跳過 shebang 後第一行註解或 docstring；CMake 第一行註解；
  JSON 取 description／summary／$comment／title，`_entry` 形狀（argv）印成「入口：…」；knowledge 的 md 取第一個標題；
  捷徑印「→ 目標」。開頭若是檔名（或夾名）接 ` - `／` — `／`：`，連檔名一起去掉；`【模組】` 去掉；取到第一個句號。
  工具夾（有 _entry 又有 _tooldef.json 或 _metainfo.json）三個契約檔併成一列 `名/`。
依賴圖：各 `<夾>/<專案>/CMakeLists.txt` 的 target_link_libraries（略過 *_main）。
純標準庫；只讀檔頭，不跑任何程式。
"""
import json
import os
import re
import subprocess
import sys

MARK = "<!-- generated by wf/tools/codemap_gen.py; edit the file header, not this table -->"
SKIP_TOP = {"thinking", "archive", "notes", "user-advice", "docs"}
SKIP_ANY_DIR = {"archive", "docs", "__pycache__", ".vscode"}
SKIP_NAMES = {".gitignore", ".gitattributes"}
MD_DIRS = {"knowledge"}          # 這些頂層夾的 .md 是內容（記憶工具讀的知識庫），要列
TOOL_PARTS = ("_entry", "_tooldef.json", "_metainfo.json")
LIMIT = 7600                     # 冊的大小上限（wf-lint OVERSIZE 是 8192）
PROG = "codemap_gen"


def warn(msg):
    print(f"{PROG}: warning: {msg}", file=sys.stderr)


def tracked(proto):
    out = subprocess.run(["git", "-C", proto, "ls-files", "-z", "--", "."],
                         capture_output=True, check=True).stdout.decode()
    files = []
    for p in out.split("\0"):
        if not p:
            continue
        parts = p.split("/")
        if len(parts) > 1 and parts[0] in SKIP_TOP:
            continue
        if any(d in SKIP_ANY_DIR for d in parts[:-1]):
            continue
        name = parts[-1]
        if name in SKIP_NAMES:
            continue
        if name.endswith(".md") and not (len(parts) > 1 and parts[0] in MD_DIRS):
            continue
        if not os.path.lexists(os.path.join(proto, p)):
            continue
        files.append(p)
    return sorted(files)


def argv_text(argv):
    out = []
    for a in argv:
        if isinstance(a, dict) and "$env" in a:
            out.append("$" + str(a["$env"]))
        elif isinstance(a, dict) and "$ref" in a:
            out.append("$ref:" + str(a["$ref"]))
        else:
            out.append(str(a))
    return " ".join(out)


def json_desc(text, entry=False):
    try:
        d = json.loads(text)
    except ValueError:
        return ""
    if isinstance(d, list) and d:
        return ("入口：`" if entry else "argv：`") + argv_text(d) + "`"
    if isinstance(d, dict):
        for k in ("description", "summary", "$comment", "title"):
            if isinstance(d.get(k), str) and d[k].strip():
                return d[k]
        if isinstance(d.get("argv"), list):
            return "入口：`" + argv_text(d["argv"]) + "`"
        if isinstance(d.get("_entry"), list):
            return "入口 `" + argv_text(d["_entry"]) + "`；鍵：" + "、".join(k for k in d if k != "_entry")
        if d:
            return "設定（鍵：" + "、".join(list(d)[:6]) + ("…" if len(d) > 6 else "") + "）"
    return ""


COMMENT = re.compile(r'^\s*(//+|/\*+|\*+(?!/)|#+|--+|;+|"""|\'\'\')\s?(.*)$')


def text_desc(text, path):
    lines = text.splitlines()[:15]
    if path.endswith(".md"):
        for ln in lines:
            if ln.startswith("#"):
                return ln.lstrip("#").strip()
        return ""
    for i, ln in enumerate(lines):
        s = ln.strip()
        if i == 0 and s.startswith("#!"):
            continue
        if not s or s.startswith("cmake_minimum_required") or "coding" in s and s.startswith("#"):
            continue
        m = COMMENT.match(ln)
        if not m:
            return ""        # 第一個有意義的行就是程式碼：沒有一句話
        body = m.group(2).strip()
        body = re.sub(r'(\*/|"""|\'\'\')\s*$', "", body).strip()
        if body:
            return body
    return ""


def clean(desc, names):
    d = " ".join(desc.split())
    for n in sorted(names, key=len, reverse=True):
        if n and d.startswith(n):
            rest = d[len(n):]
            m = re.search(r"\s+[-—–]\s+|：|:\s", rest)
            if m and m.start() <= 120:
                d = rest[m.end():].strip()
            break
    d = re.sub(r"^【[^】]*】\s*", "", d)
    cut = d.find("。")
    if 0 <= cut < len(d) - 1:
        d = d[:cut + 1]
    if len(d) > 150:
        d = d[:149] + "…"
    return d.replace("|", "\\|")


def describe(proto, rel, follow=False, comment_only=False):
    full = os.path.join(proto, rel)
    if os.path.islink(full) and not follow:
        return "→ `" + os.readlink(full) + "`", False
    try:
        with open(full, encoding="utf-8", errors="replace") as f:
            text = f.read(16384)
    except OSError:
        return "", True
    base = os.path.basename(rel)
    stem = base.split(".")[0]
    parts = rel.split("/")
    names = {base, stem, "/".join(parts[-2:]), "/".join(parts[-3:])}   # 檔頭常寫 aos/post.hpp：…
    if base in ("_entry", "CMakeLists.txt"):
        names.add(parts[-2] if len(parts) > 1 else base)
    is_json = base.endswith(".json") or (base == "_entry" and text.lstrip()[:1] in "{[")
    if comment_only and is_json:
        return "", True
    if is_json:
        d = json_desc(text, base == "_entry")
    elif base.endswith(".txt") and base != "CMakeLists.txt":
        d = ""
    else:
        d = text_desc(text, rel)
    d = clean(d, names)
    bad = not d or d in names
    return d, bad


def units(proto, files):
    """回傳 [(rel 路徑或 'x/'、涵蓋的檔)]；工具夾三個契約檔併一列。"""
    fs = set(files)
    tooldirs = set()
    for f in files:
        dname, base = os.path.split(f)
        if base == "_entry" and (os.path.join(dname, "_tooldef.json") in fs or os.path.join(dname, "_metainfo.json") in fs):
            tooldirs.add(dname)
    out, seen = [], set()
    for f in files:
        dname, base = os.path.split(f)
        if dname in tooldirs and base in TOOL_PARTS:
            if dname not in seen:
                seen.add(dname)
                cov = [os.path.join(dname, p) for p in TOOL_PARTS if os.path.join(dname, p) in fs]
                out.append((dname + "/", cov))
        else:
            out.append((f, [f]))
    return out


def deps(proto, top, files):
    rows = []
    for f in files:
        parts = f.split("/")
        if len(parts) != 3 or parts[0] != top or parts[2] != "CMakeLists.txt":
            continue
        with open(os.path.join(proto, f), encoding="utf-8", errors="replace") as fh:
            text = re.sub(r"#[^\n]*", "", fh.read())
        pub, priv = [], []
        for m in re.finditer(r"target_link_libraries\s*\(([^)]*)\)", text):
            toks = m.group(1).split()
            if not toks or toks[0].endswith("_main"):
                continue
            mode = pub
            for t in toks[1:]:
                if t in ("PUBLIC", "INTERFACE"):
                    mode = pub
                elif t == "PRIVATE":
                    mode = priv
                elif t not in mode and not t.startswith("$"):
                    mode.append(t)
        if pub or priv:
            rows.append((parts[1], pub, priv))
    return rows


def section_key(rel, top):
    parts = rel.rstrip("/").split("/")
    if top == "root":
        return ""
    # parts[0] == top；第二層若是夾就當段，否則併進頂層段
    if len(parts) >= 3:
        return parts[1]
    return ""


def render(proto, top, files, stats):
    us = units(proto, files)
    sections = {}
    for rel, cov in us:
        if rel.endswith("/"):
            # 工具夾：_entry 的註解 → _tooldef.description → _metainfo.summary（捷徑跟過去）→ _entry 的 argv
            d, bad = describe(proto, rel + "_entry", follow=True, comment_only=True)
            for alt, co in (("_tooldef.json", False), ("_metainfo.json", False), ("_entry", False)):
                if not bad:
                    break
                if rel + alt in cov:
                    d, bad = describe(proto, rel + alt, follow=True, comment_only=co)
        else:
            d, bad = describe(proto, rel)
        if bad:
            stats["warn"].append(rel)
            d = d or "（檔頭沒有一句話）"
        key = section_key(rel, top)
        sections.setdefault(key, []).append((rel, d))
        stats["rows"] += 1
        stats["covered"] += len(cov)
    blocks = []
    dep = deps(proto, top, files) if top != "root" else []
    if dep:
        b = ["## 依賴（各 `CMakeLists.txt` 的 `target_link_libraries`）", "",
             "| 專案 | 公開 | 私有 |", "|---|---|---|"]
        for p, pub, priv in dep:
            b.append(f"| `{p}` | {'、'.join(pub) or '—'} | {'、'.join(priv) or '—'} |")
        blocks.append(("", "\n".join(b)))
    for key in sorted(sections):
        base = top + "/" + (key + "/" if key else "") if top != "root" else ""
        title = f"`proto8/{base}`" if base else "`proto8/` 頂層單檔"
        b = [f"## {title}", "", "| 檔 | 負責什麼 |", "|---|---|"]
        for rel, d in sections[key]:
            shown = rel[len(base):] if base and rel.startswith(base) else rel
            b.append(f"| [`{shown}`](../../../../../proto8/{rel}) | {d} |")
        blocks.append((key, "\n".join(b)))
    return blocks


def books(proto, files):
    groups = {}
    for f in files:
        top = f.split("/")[0] if "/" in f else "root"
        groups.setdefault(top, []).append(f)
    stats = {"rows": 0, "covered": 0, "warn": []}
    out, index = {}, []
    for top in sorted(groups):
        r0, c0 = stats["rows"], stats["covered"]
        blocks = render(proto, top, groups[top], stats)
        chunks, cur = [], []
        for key, b in blocks:
            if cur and sum(len(x[1].encode()) for x in cur) + len(b.encode()) > LIMIT - 500:
                chunks.append(cur)
                cur = []
            cur.append((key, b))
        if cur:
            chunks.append(cur)
        names = [f"{top}.md"] + [f"{top}-{i}.md" for i in range(2, len(chunks) + 1)]
        what = f"`proto8/{top}/`" if top != "root" else "`proto8/` 頂層單檔"
        for i, ch in enumerate(chunks):
            nav = "← [code map](../../code-map.md)｜[生成冊索引](README.md)"
            if i > 0:
                nav += f"｜上一份 [{names[i-1][:-3]}]({names[i-1]})"
            if i + 1 < len(chunks):
                nav += f"｜下一份 [{names[i+1][:-3]}]({names[i+1]})"
            head = [MARK, nav, "", f"# {what} 逐檔表（生成，{i+1}／{len(chunks)}）", "",
                    "一句話取自各檔檔頭；要改說明去改檔頭，再跑 `python3 wf/tools/codemap_gen.py --apply`。"
                    "工具夾（`_entry`＋`_tooldef.json`＋`_metainfo.json`）併成一列。", ""]
            out[names[i]] = "\n".join(head) + "\n" + "\n\n".join(b for _, b in ch) + "\n"
            keys = ["依賴圖" if b.startswith("## 依賴") else (f"`{k}/`" if k else "頂層") for k, b in ch]
            index.append((names[i], what, "、".join(keys),
                          f"{stats['rows'] - r0}／{stats['covered'] - c0}" if i == 0 else ""))
    idx = [MARK, "← [code map](../../code-map.md)｜[code-map 分冊導覽](../README.md)", "",
           "# proto8 逐檔 code map 生成冊索引", "",
           f"`wf/tools/codemap_gen.py` 從 proto8 進版控的檔的檔頭一句話生成：{len(files)} 個檔、"
           f"{stats['rows']} 列（工具夾三個契約檔併一列）。一個 proto8 頂層夾一冊，太大照第二層夾切成 `-2`、`-3`…；"
           "「列／檔」寫在每個夾的第一冊。", "",
           "| 冊 | 夾 | 段 | 列／檔 |", "|---|---|---|---|"]
    for n, what, keys, rc in index:
        idx.append(f"| [{n[:-3]}]({n}) | {what} | {keys} | {rc} |")
    out["README.md"] = "\n".join(idx) + "\n"
    return out, stats, len(files)


def main(argv):
    apply = "--apply" in argv
    quiet = "--quiet" in argv or "-q" in argv
    if "-h" in argv or "--help" in argv:
        print(__doc__.split("\n\n")[0] + "\n\n" + "\n".join(__doc__.split("\n")[2:6]))
        return 0
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    if "--root" in argv:
        i = argv.index("--root")
        if i + 1 >= len(argv):
            print(f"{PROG}: error: ArgumentsBad --root needs a path (usage: codemap_gen.py [--root REPO] [--apply] [--quiet])", file=sys.stderr)
            return 1
        root = os.path.abspath(argv[i + 1])
    for a in argv:
        if a.startswith("-") and a not in ("--apply", "--quiet", "-q", "--root"):
            print(f"{PROG}: error: FlagUnknown {a} (usage: codemap_gen.py [--root REPO] [--apply] [--quiet])", file=sys.stderr)
            return 1
    proto = os.path.join(root, "proto8")
    outdir = os.path.join(root, "wf", "workflows", "common", "code-map", "proto8")
    if not os.path.isdir(proto):
        print(f"{PROG}: error: NotFound {proto}", file=sys.stderr)
        return 1
    files = tracked(proto)
    want, stats, nfiles = books(proto, files)
    have = {}
    if os.path.isdir(outdir):
        for n in sorted(os.listdir(outdir)):
            p = os.path.join(outdir, n)
            if n.endswith(".md") and os.path.isfile(p):
                with open(p, encoding="utf-8") as f:
                    t = f.read()
                if t.startswith(MARK):
                    have[n] = t
    if not quiet:
        for w in stats["warn"]:
            warn(f"proto8/{w}: no one-line description in the file header")
    stale = sorted(n for n in have if n not in want)
    diff = sorted(n for n in want if have.get(n) != want[n])
    if apply:
        os.makedirs(outdir, exist_ok=True)
        for n in diff:
            with open(os.path.join(outdir, n), "w", encoding="utf-8") as f:
                f.write(want[n])
        for n in stale:
            os.remove(os.path.join(outdir, n))
        if not quiet:
            print(f"{PROG}: {nfiles} files, {stats['covered']} covered, {stats['rows']} rows, {len(want)} books;"
                  f" wrote {len(diff)}, removed {len(stale)}, {len(stats['warn'])} warnings")
        return 0
    bad = 0
    for n in diff:
        bad += 1
        kind = "missing" if n not in have else "differs"
        print(f"{PROG}: error: CodemapStale code-map/proto8/{n} {kind} (run wf/tools/codemap_gen.py --apply)")
        if n in have and not quiet:
            import difflib
            for ln in list(difflib.unified_diff(have[n].splitlines(), want[n].splitlines(), "committed", "generated", n=0, lineterm=""))[2:12]:
                print("    " + ln)
    for n in stale:
        bad += 1
        print(f"{PROG}: error: CodemapStale code-map/proto8/{n} no longer generated (run wf/tools/codemap_gen.py --apply)")
    if not quiet:
        print(f"{PROG}: {nfiles} files, {stats['covered']} covered, {stats['rows']} rows, {len(want)} books, {bad} stale, {len(stats['warn'])} warnings")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
