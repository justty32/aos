# 測 08「daemon 的 stop 沒有時間上限」與「stopping 中下 sleep 改送 TERM、退後留 stopped」（03:9、08:37）。
import sys, time; sys.path.insert(0, __file__.rsplit("/",1)[0])
from importlib import import_module; C = import_module("A-common")
d = C.D("stopnolimit", {"interval_ms": 50, "procs": {"j": {"exec": {"argv": ["sleep", "1000"]}, "interval_ms": 0}}})
d.start()
time.sleep(1.5); print("t1.5", d.row("j")["phase"], d.row("j")["pid"])
d.ctl({"procs_stopped": ["j"]})
time.sleep(4); r = d.row("j"); print("after stop 4s:", r["phase"], r.get("stop_mode"))
d.ctl({"procs_stopped": ["j"], "procs_slept": ["j"]})
t = time.time()
while time.time() - t < 15 and d.row("j")["phase"] == "stopping": time.sleep(.1)
r = d.row("j"); print("after sleep %.1fs:" % (time.time() - t), r["phase"], r["code"], r["signal"], r["reason"])
d.ctl({}); time.sleep(1.5); r = d.row("j"); print("procs_ctl cleared:", r["phase"], r["pid"])
d.shutdown(); print("rows after shutdown", {k: v["phase"] for k, v in d.rows().items()})
